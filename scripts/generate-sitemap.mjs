// Generates public/sitemap.xml.
//
// Every URL used to carry the same hand-typed <lastmod>, which tells Google
// nothing and eventually gets ignored. Each entry's date now comes from the
// last commit that touched the page's own source file, so a page's lastmod
// changes only when the page does.
//
// Run by `npm run build` before `vite build`, and available on its own as
// `npm run sitemap`. If git history is unavailable (a Docker build that does
// not copy .git, a tarball checkout) the existing file is kept rather than
// being rewritten with wrong dates.
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import blogs from '../src/data/blogs.js';
import { SITE_URL, SITEMAP_PAGES } from '../src/data/schema.js';

const ROOT = path.resolve(fileURLToPath(new URL('..', import.meta.url)));
const OUTPUT = path.join(ROOT, 'public', 'sitemap.xml');

const gitAvailable = () => {
    try {
        execFileSync('git', ['rev-parse', '--is-inside-work-tree'], {
            cwd: ROOT,
            stdio: 'ignore',
        });
        return true;
    } catch {
        return false;
    }
};

// Last commit date (YYYY-MM-DD) across the given files. Uncommitted edits
// are reported as today, so a page being changed right now still gets a
// fresh date.
const lastModified = (files) => {
    let newest = null;

    for (const file of files) {
        const absolute = path.join(ROOT, file);
        if (!fs.existsSync(absolute)) {
            throw new Error(`sitemap: source file missing: ${file}`);
        }

        const dirty = execFileSync('git', ['status', '--porcelain', '--', file], {
            cwd: ROOT,
            encoding: 'utf8',
        }).trim();

        const date = dirty
            ? new Date().toISOString().slice(0, 10)
            : execFileSync('git', ['log', '-1', '--format=%cs', '--', file], {
                cwd: ROOT,
                encoding: 'utf8',
            }).trim();

        if (!/^\d{4}-\d{2}-\d{2}$/.test(date)) {
            throw new Error(`sitemap: no commit date for ${file}`);
        }
        if (!newest || date > newest) newest = date;
    }

    return newest;
};

const urlEntry = ({ loc, lastmod, changefreq, priority }) =>
    [
        '  <url>',
        `    <loc>${loc}</loc>`,
        `    <lastmod>${lastmod}</lastmod>`,
        `    <changefreq>${changefreq}</changefreq>`,
        `    <priority>${priority}</priority>`,
        '  </url>',
    ].join('\n');

const main = () => {
    if (!gitAvailable()) {
        console.log('sitemap: no git history available — keeping public/sitemap.xml as is');
        return;
    }

    const entries = [];

    // Static pages. Each one's date comes from its own page component, plus
    // the layout/footer so a navigation change refreshes every page.
    for (const page of SITEMAP_PAGES) {
        entries.push({
            loc: page.path === '/' ? `${SITE_URL}/` : `${SITE_URL}${page.path}`,
            lastmod: lastModified([page.source, 'src/components/Layout.jsx']),
            changefreq: page.changefreq,
            priority: page.priority,
        });
    }

    // Blog posts carry their own dates: `updated` when a post has been
    // revised, otherwise its publish date. A single shared blogs.js gives no
    // per-post git history, and stamping every post with the date that file
    // last changed is exactly the uniform lastmod that made the old sitemap
    // worthless.
    const postDate = post => post.updated || post.date;

    const blogIndex = entries.find(entry => entry.loc === `${SITE_URL}/blog`);
    const newestPost = blogs.map(postDate).sort().at(-1);
    if (blogIndex && newestPost > blogIndex.lastmod) blogIndex.lastmod = newestPost;

    for (const post of blogs) {
        entries.push({
            loc: `${SITE_URL}/blog/${post.slug}`,
            lastmod: postDate(post),
            changefreq: 'monthly',
            priority: '0.7',
        });
    }

    const xml = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<!-- Generated by scripts/generate-sitemap.mjs. Do not edit by hand. -->',
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
        entries.map(urlEntry).join('\n\n'),
        '</urlset>',
        '',
    ].join('\n');

    fs.writeFileSync(OUTPUT, xml);
    console.log(`Generated public/sitemap.xml with ${entries.length} URLs`);
};

main();
